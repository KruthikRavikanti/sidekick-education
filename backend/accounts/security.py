"""Account/session primitives. All mutable security decisions use SQLite transactions."""
import hashlib
import hmac
import secrets
import sqlite3
import time
import uuid
from dataclasses import dataclass
from typing import Protocol

from argon2 import PasswordHasher, Type
from argon2.exceptions import InvalidHashError, VerificationError
from email_validator import EmailNotValidError, validate_email
from fastapi import Request, Response

from .database import Database
from .models import KidView, SessionView
from .settings import Settings


class Clock(Protocol):
    def now(self) -> float: ...


class SystemClock:
    def now(self):
        return time.time()


class AccountError(Exception):
    def __init__(self, code: str, message: str, status: int = 400):
        self.code, self.message, self.status = code, message, status
        super().__init__(code)


def digest(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def kid_view(row) -> KidView:
    return KidView(id=row['id'], firstName=row['first_name'], grade=row['grade'], avatarKey=row['avatar_key'])


@dataclass
class SessionRecord:
    token_digest: str
    account_id: str
    mode: str
    active_kid_profile_id: str | None
    parent_expires_at: float | None
    version: int


class SecurityContext:
    def __init__(self, settings: Settings | None = None, clock: Clock | None = None):
        self.settings = settings or Settings.from_env()
        self.clock = clock or SystemClock()
        self.db = Database(self.settings.database_url)
        # OWASP Argon2id baseline: m=19MiB, t=2, p=1; salts generated by argon2-cffi.
        self.hasher = PasswordHasher(time_cost=2, memory_cost=19456, parallelism=1, salt_len=16, type=Type.ID)
        self._dummy_hash = self.hasher.hash(secrets.token_urlsafe(24))

    @classmethod
    def from_env(cls):
        return cls(Settings.from_env())

    def hash_secret(self, value: str):
        return self.hasher.hash(value)

    def verify_secret(self, encoded: str | None, value: str):
        try:
            return self.hasher.verify(encoded or self._dummy_hash, value)
        except (VerificationError, InvalidHashError):
            return False

    def normalize_email(self, value: str):
        try:
            return validate_email(value.strip(), check_deliverability=False, test_environment=self.settings.app_env == 'test').normalized.casefold()
        except EmailNotValidError:
            raise AccountError('invalid_email', 'Enter a valid email address.') from None

    def validate_password(self, value: str):
        if self.settings.password_policy == 'dev':
            if not value:
                raise AccountError('weak_password', 'Enter a password.')
            return
        # TODO: Turn on strict password rules before pilot.
        common = {'password', 'password123', 'passwordpassword', '123456789012', 'qwertyuiop123'}
        if len(value) < 12 or len(set(value)) < 4 or value.casefold() in common:
            raise AccountError('weak_password', 'Use at least 12 characters and avoid common passwords.')

    def rate_limit(self, connection, namespace: str, identifier: str, limit: int, window: int = 300):
        now = self.clock.now()
        key = digest(namespace + ':' + identifier)
        row = connection.execute('SELECT * FROM rate_limits WHERE key=?', (key,)).fetchone()
        if not row or row['window_start'] + window <= now:
            connection.execute('INSERT INTO rate_limits VALUES (?,1,?) ON CONFLICT(key) DO UPDATE SET attempts=1,window_start=excluded.window_start', (key, now))
            return
        if row['attempts'] >= limit:
            raise AccountError('rate_limited', 'Too many attempts. Please try again in five minutes.', 429)
        connection.execute('UPDATE rate_limits SET attempts=attempts+1 WHERE key=?', (key,))

    def session(self, request: Request) -> SessionRecord:
        token = request.cookies.get(self.settings.session_cookie, '')
        if not token or len(token) > 200:
            raise AccountError('unauthenticated', 'Please log in to continue.', 401)
        now = self.clock.now()
        with self.db.transaction() as connection:
            row = connection.execute('SELECT * FROM sessions WHERE token_digest=? AND revoked_at IS NULL AND expires_at>?', (digest(token), now)).fetchone()
            if not row:
                raise AccountError('unauthenticated', 'Please log in to continue.', 401)
            if row['mode'] == 'parent' and (row['parent_expires_at'] is None or row['parent_expires_at'] <= now):
                connection.execute("UPDATE sessions SET mode='picker',active_kid_profile_id=NULL,parent_last_activity_at=NULL,parent_expires_at=NULL,version=version+1 WHERE token_digest=?", (row['token_digest'],))
                row = connection.execute('SELECT * FROM sessions WHERE token_digest=?', (row['token_digest'],)).fetchone()
            return SessionRecord(row['token_digest'], row['account_id'], row['mode'], row['active_kid_profile_id'], row['parent_expires_at'], row['version'])

    def session_view(self, session: SessionRecord) -> SessionView:
        active = None
        with self.db.transaction() as connection:
            self.assert_active(connection, session, session.mode)
            if session.mode == 'kid' and session.active_kid_profile_id:
                kid = connection.execute('SELECT * FROM kid_profiles WHERE id=? AND account_id=?', (session.active_kid_profile_id, session.account_id)).fetchone()
                if not kid:
                    raise AccountError('kid_required', 'Choose a child profile to continue.', 403)
                active = kid_view(kid)
        return SessionView(mode=session.mode, activeKidProfileId=session.active_kid_profile_id, activeKid=active, parentExpiresAt=session.parent_expires_at, version=session.version)

    def _cookie(self, response: Response, name: str, value: str, max_age: int):
        response.set_cookie(name, value, max_age=max_age, httponly=True, secure=self.settings.cookie_secure, samesite='lax', path='/')

    def issue_csrf(self, response: Response, session_digest: str | None):
        token = secrets.token_urlsafe(32)
        with self.db.transaction() as connection:
            connection.execute('INSERT INTO csrf_tokens VALUES (?,?,?)', (digest(token), session_digest, self.clock.now() + self.settings.session_seconds))
        self._cookie(response, self.settings.csrf_cookie, token, self.settings.session_seconds)
        return token

    def csrf(self, request: Request, response: Response):
        session_digest = None
        if request.cookies.get(self.settings.session_cookie):
            try:
                session_digest = self.session(request).token_digest
            except AccountError:
                response.delete_cookie(self.settings.session_cookie, path='/', secure=self.settings.cookie_secure, httponly=True, samesite='lax')
        token = request.cookies.get(self.settings.csrf_cookie, '')
        if token and len(token) < 200:
            with self.db.transaction() as connection:
                row = connection.execute('SELECT * FROM csrf_tokens WHERE token_digest=? AND expires_at>?', (digest(token), self.clock.now())).fetchone()
            if row and row['session_digest'] == session_digest:
                return token
        return self.issue_csrf(response, session_digest)

    def validate_csrf(self, request: Request):
        origin = request.headers.get('origin', '')
        if origin not in self.settings.trusted_origins or request.headers.get('sec-fetch-site') == 'cross-site':
            raise AccountError('csrf_failed', 'This request could not be verified. Refresh the page and try again.', 403)
        token = request.headers.get('x-csrf-token', '')
        cookie = request.cookies.get(self.settings.csrf_cookie, '')
        if not token or len(token) > 200 or len(cookie) > 200 or not token.isascii() or not cookie.isascii() or not hmac.compare_digest(token, cookie):
            raise AccountError('csrf_failed', 'This request could not be verified. Refresh the page and try again.', 403)
        session_digest = None
        session_cookie = request.cookies.get(self.settings.session_cookie)
        if session_cookie:
            # Tokens bound to revoked/expired sessions cannot authorize even public operations.
            session_digest = self.session(request).token_digest
        with self.db.transaction() as connection:
            row = connection.execute('SELECT * FROM csrf_tokens WHERE token_digest=? AND expires_at>?', (digest(token), self.clock.now())).fetchone()
        if not row or row['session_digest'] != session_digest:
            raise AccountError('csrf_failed', 'This request could not be verified. Refresh the page and try again.', 403)

    def new_session(self, connection, account_id: str):
        token = secrets.token_urlsafe(32)
        now = self.clock.now()
        connection.execute('INSERT INTO sessions(token_digest,account_id,expires_at,created_at) VALUES (?,?,?,?)', (digest(token), account_id, now + self.settings.session_seconds, now))
        return token

    def install_session(self, request: Request, response: Response, token: str):
        self._cookie(response, self.settings.session_cookie, token, self.settings.session_seconds)
        self.issue_csrf(response, digest(token))
        with self.db.transaction() as connection:
            row = connection.execute('SELECT * FROM sessions WHERE token_digest=?', (digest(token),)).fetchone()
        return self.session_view(SessionRecord(row['token_digest'], row['account_id'], row['mode'], row['active_kid_profile_id'], row['parent_expires_at'], row['version']))

    def assert_active(self, connection, session: SessionRecord, mode: str | None = None):
        """Recheck authorization in the same transaction as a protected mutation."""
        row = connection.execute('SELECT * FROM sessions WHERE token_digest=?', (session.token_digest,)).fetchone()
        now = self.clock.now()
        if not row or row['revoked_at'] is not None or row['expires_at'] <= now:
            raise AccountError('unauthenticated', 'Please log in to continue.', 401)
        if mode == 'parent' and (row['mode'] != 'parent' or row['parent_expires_at'] is None or row['parent_expires_at'] <= now):
            raise AccountError('parent_required', 'Enter your parent PIN to continue.', 403)
        if mode == 'kid' and row['mode'] != 'kid':
            raise AccountError('kid_required', 'Choose a child profile to continue.', 403)
        if row['version'] != session.version:
            raise AccountError('profile_changed', 'Your profile changed. Refresh the page and try again.', 409)
        return row

    def owned_kid(self, connection, account_id: str, kid_id: str):
        row = connection.execute('SELECT * FROM kid_profiles WHERE id=? AND account_id=?', (kid_id, account_id)).fetchone()
        if not row:
            raise AccountError('not_found', 'That child profile was not found.', 404)
        return row

    def account_password(self, connection, account_id: str, password: str):
        # Count password verification attempts across sessions and all password-gated actions.
        self.rate_limit(connection, 'password', account_id, 5)
        account = connection.execute('SELECT * FROM accounts WHERE id=?', (account_id,)).fetchone()
        return bool(account and self.verify_secret(account['password_hash'], password))

    def invalidate_parent_unlocks(self, connection, account_id: str):
        connection.execute("UPDATE sessions SET mode='picker',active_kid_profile_id=NULL,parent_last_activity_at=NULL,parent_expires_at=NULL,version=version+1 WHERE account_id=? AND mode='parent' AND revoked_at IS NULL", (account_id,))


def get_security(request: Request) -> SecurityContext:
    if not getattr(request.app.state, 'security', None):
        request.app.state.security = SecurityContext.from_env()
    return request.app.state.security


def require_session(request: Request):
    return get_security(request).session(request)


def require_parent(request: Request):
    session = require_session(request)
    if session.mode != 'parent':
        raise AccountError('parent_required', 'Enter your parent PIN to continue.', 403)
    return session


def require_kid(request: Request):
    context = get_security(request)
    session = context.session(request)
    if session.mode != 'kid' or not session.active_kid_profile_id:
        raise AccountError('kid_required', 'Choose a child profile to continue.', 403)
    with context.db.transaction() as connection:
        context.assert_active(connection, session, 'kid')
        return kid_view(context.owned_kid(connection, session.account_id, session.active_kid_profile_id))


def require_kid_context(request: Request):
    context = get_security(request)
    session = context.session(request)
    if session.mode != 'kid' or not session.active_kid_profile_id:
        raise AccountError('kid_required', 'Choose a child profile to continue.', 403)
    with context.db.transaction() as connection:
        context.assert_active(connection, session, 'kid')
        context.owned_kid(connection, session.account_id, session.active_kid_profile_id)
    return session.active_kid_profile_id, session.version


def assert_kid_context(request: Request, kid_id: str, version: int):
    current_id, current_version = require_kid_context(request)
    if current_id != kid_id or current_version != version:
        raise AccountError('profile_changed', 'Your profile changed. Choose a worksheet again.', 409)
